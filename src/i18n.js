export function tui(lang, key, subkey) {
  const l = LANGS_WITH_FULL_UI.includes(lang) ? lang : 'en';
  const section = TUI[l] || TUI['en'];
  if (subkey) return section[key]?.[subkey] ?? TUI['en'][key]?.[subkey] ?? subkey;
  return section[key] ?? TUI['en'][key] ?? key;
}
