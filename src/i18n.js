// Detectar idioma del navegador automáticamente
export function detectBrowserLang() {
  const nav = navigator.language || navigator.languages?.[0] || 'en';
  const code = nav.split('-')[0].toLowerCase();
  return LANGUAGES.find(l => l.code === code)?.code || 'en';
}

// Guardar/cargar preferencia
export function saveLang(code) {
  try { localStorage.setItem('pl_lang', code); } catch(_) {}
}
export function loadLang() {
  try { return localStorage.getItem('pl_lang') || detectBrowserLang(); } catch(_) { return 'en'; }
}

